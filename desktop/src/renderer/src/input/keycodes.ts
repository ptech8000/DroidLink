export function mapBrowserCodeToAndroidKeycode(code: string): number | null {
  return CODE_TO_ANDROID_KEYCODE[code] ?? null;
}

export function mapBrowserModifiersToAndroidMeta(e: {
  shiftKey: boolean;
  altKey: boolean;
  ctrlKey: boolean;
  metaKey: boolean;
}): number {
  let meta = ANDROID_META.NONE;
  if (e.shiftKey) meta |= ANDROID_META.SHIFT_ON | ANDROID_META.SHIFT_LEFT_ON;
  if (e.altKey) meta |= ANDROID_META.ALT_ON | ANDROID_META.ALT_LEFT_ON;
  if (e.ctrlKey) meta |= ANDROID_META.CTRL_ON | ANDROID_META.CTRL_LEFT_ON;
  if (e.metaKey) meta |= ANDROID_META.META_ON | ANDROID_META.META_LEFT_ON;
  return meta;
}
